function tabButtons() {
  return [...document.querySelectorAll(TAB_SELECTOR)];
}

function labelOf(button) {
  return button.querySelector('.tab-btn__label')?.textContent.trim() ?? '';
}

function collapseButton() {
  const byLabel = tabButtons().find(b => !b.dataset.modkitOwn && labelOf(b) === '收起');
  if (byLabel) return byLabel;
  // Fall back to the last stock button in the strip.
  const stock = tabButtons().filter(b => !b.dataset.modkitOwn);
  return stock.length ? stock[stock.length - 1] : null;
}

// The flex column Vue renders module blocks into.
function moduleHost() {
  return document.querySelector('.module-content')
    ?? document.querySelector(BLOCK_SELECTOR)?.parentElement
    ?? null;
}

// --- the mod page -----------------------------------------------------------

function buildView() {
  const view = document.createElement('div');
  view.id = VIEW_ID;
  // .module-content stacks a .module-content__bg layer over its children, so the
  // page has to sit above it rather than merely being appended.
  view.style.cssText = `
    display: none; position: relative; z-index: 1;
    padding: 24px; overflow-y: auto; height: 100%; box-sizing: border-box;`;

  view.innerHTML = `
    <h2 style="margin:0 0 4px;font-size:20px;color:#5a4030">MOD</h2>
    <p style="margin:0 0 20px;font-size:13px;color:#a08a78">
      这一页由 mod 注入，不在原版界面里。
    </p>
    <div id="modkit-view-body"></div>`;

  return view;
}

// Mods put their UI in window.modkitEntries; this renders them.
function renderEntries() {
  const body = document.getElementById('modkit-view-body');
  if (!body) return;

  const entries = window.modkitEntries ?? [];
  body.textContent = '';

  if (!entries.length) {
    const empty = document.createElement('div');
    empty.style.cssText = 'color:#a08a78;font-size:13px';
    empty.textContent = '还没有 mod 提供内容。';
    body.appendChild(empty);
    return;
  }

  for (const entry of entries) {
    const card = document.createElement('div');
    card.style.cssText = `
      background:rgba(255,251,244,.75); border:1px solid rgba(180,150,120,.25);
      border-radius:12px; padding:14px 16px; margin-bottom:12px;`;

    const title = document.createElement('div');
    title.style.cssText = 'font-size:14px;color:#5a4030;margin-bottom:6px';
    title.textContent = entry.title;
    card.appendChild(title);

    if (entry.description) {
      const desc = document.createElement('div');
      desc.style.cssText = 'font-size:12px;color:#a08a78';
      desc.textContent = entry.description;
      card.appendChild(desc);
    }

    if (typeof entry.render === 'function') {
      try {
        const extra = entry.render();
        if (extra) card.appendChild(extra);
      } catch (err) {
        mod.warn('entry render failed', err);
      }
    }

    body.appendChild(card);
  }
}

window.modkitEntries = window.modkitEntries ?? [];
window.refreshModkitView = renderEntries;

// --- switching between the mod page and the app's pages ---------------------

function showModView() {
  const host = moduleHost();
  if (!host) return;

  for (const block of host.querySelectorAll(BLOCK_SELECTOR)) {
    if (block.id === VIEW_ID) continue;
    block.dataset.modkitHidden = '1';
    block.style.display = 'none';
  }

  let view = host.querySelector('#' + VIEW_ID);
  if (!view) {
    view = buildView();
    host.appendChild(view);
  }
  view.style.display = 'block';
  renderEntries();
}

function hideModView() {
  document.getElementById(VIEW_ID)?.style.setProperty('display', 'none');

  const host = moduleHost();
  if (!host) return;
  for (const block of host.querySelectorAll(BLOCK_SELECTOR)) {
    if (block.id === VIEW_ID || block.dataset.modkitHidden !== '1') continue;
    block.style.removeProperty('display');
    delete block.dataset.modkitHidden;
  }
}

// --- the tab button ---------------------------------------------------------

function buildTab() {
  // Clone an *inactive* button so the copy does not inherit a highlight state.
  // Falling back to any button is fine — the active class is stripped below — but
  // picking an inactive one avoids a visible flicker on insertion.
  const all = tabButtons();
  const template = all.find(b => !b.classList.contains('tab-btn--active'))
    ?? all[0];
  if (!template) return null;

  const btn = template.cloneNode(true);
  btn.id = TAB_ID;
  btn.className = 'tab-btn';       // reset: no active state, no stock modifiers
  delete btn.dataset.modkitBound;
  btn.dataset.modkitOwn = '1';
  btn.removeAttribute('style');

  const label = btn.querySelector('.tab-btn__label');
  if (label) label.textContent = 'MOD';

  const icon = btn.querySelector('.tab-btn__icon');
  if (icon) {
    // Replace the cloned sprite class with ours; installIconStyle() supplies the
    // image for both the normal and the active state.
    icon.className = `tab-btn__icon ${ICON_CLASS}`;
    icon.removeAttribute('style');
  }

  btn.addEventListener('click', () => {
    // Match the app's behaviour: exactly one tab carries .tab-btn--active. The app
    // will not set it for a button it does not know about, so set it here and
    // clear the others.
    for (const other of tabButtons()) {
      other.classList.toggle('tab-btn--active', other === btn);
    }
    showModView();
  });

  return btn;
}

// Clicking any original tab returns to the app's own content.
function bindOriginalTabs() {
  for (const btn of tabButtons()) {
    if (btn.dataset.modkitOwn || btn.dataset.modkitBound) continue;
    btn.dataset.modkitBound = '1';
    btn.addEventListener('click', () => {
      // The app's own handler has already set .tab-btn--active on the clicked tab.
      // Just make sure ours is not still highlighted as well.
      document.getElementById(TAB_ID)?.classList.remove('tab-btn--active');
      hideModView();
    });
  }
}

// --- keeping the tab in place ----------------------------------------------

let planting = false;

// The tab strip is a flex column, and the app highlights whatever sits in the
// .tab-btn--active slot. Our button is inserted immediately before 收起 so that:
//
//   * 收起 stays the last .tab-btn (the app's rule is
//     .tab-btn--active:not(:last-of-type) — the last one never lights up);
//   * our node is adjacent to a stable landmark rather than wedged among the
//     index-keyed stock buttons.
//
// Our own highlight is spelled out in installIconStyle rather than inherited,
// because the :last-of-type guard would otherwise depend on sibling order.
function ensureTab() {
  if (planting) return;
  const collapse = collapseButton();
  const bar = collapse?.parentElement;
  if (!bar || !bar.classList.contains('tab-bar')) return;

  planting = true;
  try {
    bindOriginalTabs();

    let tab = document.getElementById(TAB_ID);
    if (!tab) {
      tab = buildTab();
      if (!tab) return;
    }
    // Re-seat on every pass: Vue may have moved the strip around.
    if (tab.nextElementSibling !== collapse) {
      bar.insertBefore(tab, collapse);
    }
  } finally {
    planting = false;
  }
}

const observer = new MutationObserver(() => requestAnimationFrame(ensureTab));
observer.observe(document.body, { childList: true, subtree: true });

// Injection can land before the panel first renders, and a MutationObserver only
// fires on later changes, so poll briefly as well.
let attempts = 0;
const retry = setInterval(() => {
  ensureTab();
  if (document.getElementById(TAB_ID) || ++attempts > 150) clearInterval(retry);
}, 200);

mod.onDispose(() => observer.disconnect());
mod.onDispose(() => clearInterval(retry));
mod.onDispose(() => document.getElementById(TAB_ID)?.remove());
mod.onDispose(() => document.getElementById(VIEW_ID)?.remove());

installIconStyle();
ensureTab();
mod.log('MOD tab installed');