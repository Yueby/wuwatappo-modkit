// Adds a "MOD" entry to the settings panel's left navigation.
//
// Approach: clone a real tab button and replace only its icon and label.
//
// The first attempt built a button from scratch with class names copied by hand,
// which drifted from the app's own styling and fought with Vue over the
// .tab-btn--active class. Cloning a live button inherits every style, and we let
// the app's own click handlers manage highlighting — we only mirror it.
//
// The panel keeps its active tab in component state (not the URL) and the
// production build exposes no Vue instance, so this stays a pure DOM extension:
// the mod's page is shown by hiding the app's module blocks, and any click on an
// original tab puts them back.

if (!location.hash.includes('/panel')) return;

